/*
 * Test case: 4.1
 * Reading from an empty ring buffer must return BSP_UART_ERR_NO_DATA
 * and set outRead to 0.
 */
void TestReadBspUartEmptyBufferReturnsNoData(void)
{
    uint8_t  buf[4] = {0};
    uint16_t nRead  = 0;

    BspUartStatus_t ret = ReadBspUart(buf, 4, &nRead);

    TEST_ASSERT_EQUAL(BSP_UART_ERR_NO_DATA, ret);
    TEST_ASSERT_EQUAL_UINT16(0, nRead);
}

/*
 * Test case: 4.2
 * Requesting more bytes than available must read only the available count,
 * set outRead to the actual count, and return BSP_UART_OK.
 *
 * BUG FOUND: the current loop runs len times unconditionally, which causes
 * mCurrentNumberOfBytes (uint16_t) to underflow-wrap when len > available.
 * Fix: cap the loop at min(len, mCurrentNumberOfBytes).
 */
void TestReadBspUartReadsOnlyAvailableBytes(void)
{
    HandleBspUartIsrRx(0x11);
    HandleBspUartIsrRx(0x22);

    uint8_t  buf[10] = {0};
    uint16_t nRead   = 0;

    BspUartStatus_t ret = ReadBspUart(buf, 10, &nRead);

    TEST_ASSERT_EQUAL(BSP_UART_OK, ret);
    TEST_ASSERT_EQUAL_UINT16(2,    nRead);
    TEST_ASSERT_EQUAL_HEX8(0x11,  buf[0]);
    TEST_ASSERT_EQUAL_HEX8(0x22,  buf[1]);

    /* Available must be 0 after draining all bytes, not wrapped uint16 */
    TEST_ASSERT_EQUAL_UINT16(0, GetBspUartAvailable());
}

