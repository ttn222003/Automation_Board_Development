/* ═══════════════════════════════════════════════════════════════════════════
 * SUITE 1 – InitBspUart()
 *
 * MX_USART1_UART_Init() is generated by CubeMX and called in main.c before
 * any BSP function.  InitBspUart() therefore does NOT call HAL_UART_Init()
 * again – it only stores the already-initialised handle and sets the ready
 * flag.  No HAL mock is needed in this suite.
 * ═══════════════════════════════════════════════════════════════════════════ */

/*
 * Test case: 1.1
 * InitBspUart() with a valid handle must return BSP_UART_OK.
 * No HAL function should be called.
 */
void TestInitBspUartWithValidHandleReturnsOk(void)
{
    BspUartStatus_t ret = InitBspUart(&sDummyHandle);

    TEST_ASSERT_EQUAL(BSP_UART_OK, ret);
}

/*
 * Test case: 1.2
 * InitBspUart() with a NULL handle must return BSP_UART_ERR_NULL_PTR.
 * No HAL function should be called.
 */
void TestInitBspUartNullHandleReturnsError(void)
{
    BspUartStatus_t ret = InitBspUart(NULL);

    TEST_ASSERT_EQUAL(BSP_UART_ERR_NULL_PTR, ret);
}

/*
 * Test case: 1.3
 * Calling SendBspUart() before InitBspUart() must return BSP_UART_ERR_NOT_INIT.
 * ResetBspUartState() in setUp guarantees the init flag is cleared.
 */
void TestSendBspUartBeforeInitReturnsNotInit(void)
{
    uint8_t         data[] = {0x01, 0x02};
    BspUartStatus_t ret    = SendBspUart(&sDummyHandle, data, 2);

    TEST_ASSERT_EQUAL(BSP_UART_ERR_NOT_INIT, ret);
}

/*
 * Test case: 1.4
 * After a successful InitBspUart(), calling ResetBspUartState() and then
 * SendBspUart() must still return BSP_UART_ERR_NOT_INIT.
 *
 * This test exposes the missing init flag: if ResetBspUartState() does not
 * clear a dedicated mIsInitialized field, mCurrentStatus stays BSP_UART_OK
 * after reset and SendBspUart() skips the NOT_INIT guard entirely.
 */
void TestSendBspUartAfterResetReturnsNotInit(void)
{
    InitBspUart(&sDummyHandle);   /* mCurrentStatus = BSP_UART_OK */
    ResetBspUartState();          /* must also clear the init flag */

    uint8_t         data[] = {0x01, 0x02};
    BspUartStatus_t ret    = SendBspUart(&sDummyHandle, data, 2);

    TEST_ASSERT_EQUAL(BSP_UART_ERR_NOT_INIT, ret);
}

